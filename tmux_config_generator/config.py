"""Config model, tmux.conf generation and (best-effort) parsing."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date

from .options import CATEGORIES, OPTIONS, OPTIONS_BY_NAME, Option

# Options whose values contain backslash escapes that tmux should interpret
# (e.g. "\e[1;5A"); these are written in double quotes without escaping "\".
BACKSLASH_ESCAPED = {"user-keys"}

# Array options that must always be written with explicit indexes, because
# tmux splits unindexed values on commas.
INDEX_ONLY = {"status-format"}

KEY_TABLES = ["prefix", "root", "copy-mode", "copy-mode-vi"]

_SAFE = re.compile(r"^[A-Za-z0-9_./:@+=,^*!&()<>?\[\]|-]+$")


def quote(value: str) -> str:
    """Quote *value* so tmux's config parser reads it back verbatim."""
    if value and _SAFE.match(value):
        return value
    if "'" not in value:
        return f"'{value}'"
    escaped = (value.replace("\\", "\\\\").replace('"', '\\"')
               .replace("$", "\\$"))
    return f'"{escaped}"'


def quote_escaped(value: str) -> str:
    """Double-quote *value* leaving backslash escapes for tmux to expand."""
    return '"' + value.replace('"', '\\"').replace("$", "\\$") + '"'


def quote_key(key: str) -> str:
    """Quote a key name for bind-key/unbind-key."""
    if key == "-":
        return key
    return quote(key)


@dataclass
class Binding:
    key: str
    command: str
    table: str = "prefix"
    repeat: bool = False
    note: str = ""

    def render(self) -> str:
        parts = ["bind"]
        if self.repeat:
            parts.append("-r")
        if self.note:
            parts += ["-N", quote(self.note)]
        if self.table == "root":
            parts.append("-n")
        elif self.table != "prefix":
            parts += ["-T", quote(self.table)]
        parts += [quote_key(self.key), self.command.strip()]
        return " ".join(parts)


@dataclass
class Unbind:
    key: str  # empty string means "all keys in the table"
    table: str = "prefix"

    def render(self) -> str:
        parts = ["unbind"]
        if not self.key:
            parts.append("-a")
        if self.table == "root":
            parts.append("-n")
        elif self.table != "prefix" or not self.key:
            parts += ["-T", quote(self.table)]
        if self.key:
            parts.append(quote_key(self.key))
        return " ".join(parts)


@dataclass
class Config:
    # option name -> value (str, or list[str] for list options). Only
    # options present here are written to the file.
    values: dict = field(default_factory=dict)
    # list options that append to tmux's defaults instead of replacing them
    list_append: set = field(default_factory=set)
    unbinds: list = field(default_factory=list)
    bindings: list = field(default_factory=list)
    extra: str = ""

    def set(self, name: str, value) -> None:
        self.values[name] = value

    def unset(self, name: str) -> None:
        self.values.pop(name, None)
        self.list_append.discard(name)


def render_option(opt: Option, value, append: bool = False) -> list[str]:
    q = quote_escaped if opt.name in BACKSLASH_ESCAPED else quote
    if opt.type != "list":
        return [f"set {opt.flags} {opt.name} {q(str(value))}"]
    items = [v for v in value if v != ""]
    if append and opt.name not in INDEX_ONLY:
        aflags = "-a" + opt.flags[1:]
        return [f"set {aflags} {opt.name} {q(v)}" for v in items]
    lines = [f"set {opt.flags} {opt.name} ''"]
    lines += [f"set {opt.flags} {opt.name}[{i}] {q(v)}"
              for i, v in enumerate(items)]
    return lines


def generate(cfg: Config, header: bool = True) -> str:
    out: list[str] = []
    if header:
        out += ["# tmux configuration",
                f"# Generated by tmux-config-generator on {date.today():%Y-%m-%d}",
                ""]
    for cat, title in CATEGORIES:
        lines = []
        for opt in OPTIONS:
            if opt.category == cat and opt.name in cfg.values:
                lines += render_option(opt, cfg.values[opt.name],
                                       opt.name in cfg.list_append)
        if lines:
            out += [f"# --- {title} ---", *lines, ""]
    if cfg.unbinds:
        out += ["# --- Unbound keys ---", *(u.render() for u in cfg.unbinds), ""]
    if cfg.bindings:
        out.append("# --- Key bindings ---")
        for table in _tables_in_order(cfg.bindings):
            out += [b.render() for b in cfg.bindings if b.table == table]
        out.append("")
    if cfg.extra.strip():
        out += ["# --- Custom ---", cfg.extra.strip("\n"), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def _tables_in_order(bindings) -> list[str]:
    tables = [t for t in KEY_TABLES if any(b.table == t for b in bindings)]
    for b in bindings:
        if b.table not in tables:
            tables.append(b.table)
    return tables


